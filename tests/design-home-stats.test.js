import 'fake-indexeddb/auto';
import { beforeEach, afterEach, it, expect, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import path from 'node:path';
vi.mock('../src/adapters/firebase/sync-facade.js', () => ({ status: { user:null,state:'sin sesión',configured:false,reqs:[] }, onStatus:()=>()=>{} }));
let routes, store, engine, screen;
beforeEach(async () => {
  vi.resetModules(); localStorage.clear();
  document.body.innerHTML = '<main id="app"></main>';
  vi.stubGlobal('scrollTo', vi.fn()); vi.stubGlobal('matchMedia',()=>({matches:false}));
  vi.stubGlobal('fetch', async url => ({ ok:true, json:async()=>JSON.parse(readFileSync(path.join('public',String(url)), 'utf8')) }));
  store = await import('../src/adapters/local/legacy-store.js'); engine = await import('../src/core/application/legacy-engine.js');
  routes={}; screen={};
  (await import('../src/features/home/legacy.js')).registerHome({routes,go:vi.fn(),saludo:()=> 'Hola', quickSession:vi.fn(),startRepaso:vi.fn(),openMenu:vi.fn(),dominioTemas:engine.dominioTemas,falladasIds:engine.falladasIds},screen);
  (await import('../src/features/stats/legacy.js')).registerStats({routes,go:vi.fn(),trapTest:vi.fn(),startRun:vi.fn()});
});
afterEach(()=> { screen.cleanup?.(); vi.unstubAllGlobals(); });
it('prioriza retomar, repasar y falladas, agrupa entrenamientos y no presenta una fecha oficial inventada', async()=> {
  engine.state.run={items:[{}],idx:0};
  await routes.home();
  expect(document.querySelector('#continue')).not.toBeNull();
  expect(document.querySelector('#trampas').closest('details').querySelector('summary').textContent).toContain('Entrenamientos');
  expect(document.querySelector('#app').textContent).toContain('Configurar fecha objetivo');
  expect(document.querySelector('#app').textContent).not.toContain('al examen');
  expect(document.querySelector('#quick')).not.toBeNull();
});
it('busca temas sin perder marcas, bloque abierto ni foco al actualizar progreso', async()=> {
  await routes.temario();
  const search=document.querySelector('#topic-search'); expect(search).not.toBeNull();
  search.value='T1.01'; search.dispatchEvent(new Event('input',{bubbles:true}));
  const check=document.querySelector('[data-t="T1.01"]');
  check.closest('details').open=true; check.focus(); check.click();
  expect(store.getSeen()).toContain('T1.01');
  expect(document.querySelector('#topic-search').value).toBe('T1.01');
  expect(document.activeElement.dataset.t).toBe('T1.01');
  expect(document.querySelector('[data-t="T1.01"]').closest('details').open).toBe(true);
  expect(document.querySelectorAll('[data-t]')).toHaveLength(1);
  expect(document.querySelector('#app').textContent).toContain('preguntas contestadas');
});
it('separa las secciones de progreso sin perder el historial y comunica selecciones y leyenda', async()=> {
  await routes.stats();
  const sims=document.querySelector('[data-stats-view="sims"]'); expect(sims).not.toBeNull();
  expect(document.querySelector('#stats-summary').textContent).toContain('Repasar hoy');
  sims.click(); expect(sims.getAttribute('aria-pressed')).toBe('true');
  expect(document.querySelector('#stats-sims').hidden).toBe(false);
  expect(document.querySelector('#stats-temas').hidden).toBe(true);
  document.querySelector('[data-stats-view="evo"]').click();
  document.querySelector('#evt').focus(); document.querySelector('#evt').click();
  expect(document.activeElement.id).toBe('evt');
  expect(document.querySelector('#evo table')).not.toBeNull();
  expect(document.querySelector('#evm [data-v="acierto"]').getAttribute('aria-pressed')).toBe('true');
  expect(document.querySelector('#mapa .dmsum').textContent).toContain('Sin datos');
  expect(document.querySelector('#app').textContent).toContain('Últimas sesiones');
});
it('buscar y navegar no modifica el progreso y una cuenta nueva no recibe la pantalla de la anterior', async()=> {
  store.setSeen(['T1.01']);
  const before=store.exportAll();
  await routes.temario();
  const search=document.querySelector('#topic-search');
  search.value='ningun-tema-9472'; search.dispatchEvent(new Event('input'));
  expect(document.querySelectorAll('[data-t]')).toHaveLength(0);
  expect(store.getSeen()).toEqual(['T1.01']);
  await routes.stats();
  document.querySelector('[data-stats-view="sims"]').click();
  expect(store.exportAll()).toBe(before);
  const data=await import('../src/adapters/http/legacy-data.js');
  let finish;
  const spy=vi.spyOn(data,'dueList').mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve;}));
  document.querySelector('#app').innerHTML='<p>Nueva pantalla</p>';
  const pending=routes.home();
  await vi.waitFor(()=>expect(finish).toBeTypeOf('function'));
  store.switchAccount('otra-cuenta'); finish([]); await pending;
  expect(document.querySelector('#app').textContent).toBe('Nueva pantalla');
  spy.mockRestore();
});
